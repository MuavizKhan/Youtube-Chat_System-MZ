"""Shared parsing and sanitization for YouTube transcript timestamps.

Timestamp claims generated by an LLM are untrusted prose. Production responses
must derive their displayed timestamp metadata from retrieved source intervals
or a validated temporal-retrieval trace. This module contains only deterministic
format parsing and removal helpers; it does not select evidence or know videos.
"""

from __future__ import annotations

from dataclasses import dataclass
import re


# YouTube timestamps are normally MM:SS and become HH:MM:SS for long videos.
_TIMESTAMP_VALUE = r"(?:\d{1,3}:)?\d{1,2}:\d{2}"
_TIMESTAMP_SEPARATOR = r"(?:[-\u2010\u2011\u2012\u2013\u2014\u2015\u2212\ufe58\ufe63\uff0d]|\bto\b|\band\b|&|/)"
TIMESTAMP_RANGE_PATTERN = re.compile(
    rf"(?<![\d:])(?P<start>{_TIMESTAMP_VALUE})"
    rf"\s*{_TIMESTAMP_SEPARATOR}\s*"
    rf"(?P<end>{_TIMESTAMP_VALUE})(?![\d:])",
    re.IGNORECASE,
)
TIMESTAMP_VALUE_PATTERN = re.compile(
    rf"(?<![\d:]){_TIMESTAMP_VALUE}(?![\d:])"
)
_TIMESTAMP_SUMMARY_LINE_PATTERN = re.compile(
    r"(?im)^[ \t]*Relevant timestamps?[ \t]*:[^\r\n]*(?:\r?\n|$)"
)
_TIMESTAMP_LOCATION_CUE_SUFFIX_PATTERN = re.compile(
    r"\b(?:at|around|about|approximately|roughly|near|from|between|to|until|"
    r"in|within|during|by|timestamp(?:s| range(?:s)?)?|timecode|"
    r"time(?:\s*stamp)?|minute|mark)\s*:?\s*$"
    r"|(?:عند|حوالي|قرابة|تقريبًا|تقريبا|من|حتى|في|لدى|लगभग|करीब|पर|से|तक|में)\s*$",
    re.IGNORECASE,
)
_TIMESTAMP_LOCATION_CUE_WORD_PATTERN = re.compile(
    r"\b(?:timestamp(?:s)?|timecode|time\s*stamp|mark)\b",
    re.IGNORECASE,
)
_TIMESTAMP_SENTENCE_SPLIT_PATTERN = re.compile(r"(?<=[.!?؟؛;])\s+")
_TIMESTAMP_STRIP_EDGE_CHARS = " \t,;:—–-()[]{}•*"


@dataclass(frozen=True, slots=True)
class ParsedTimestampRange:
    """A validated timestamp interval expressed in the answer."""

    raw: str
    start_text: str
    end_text: str
    start_seconds: int
    end_seconds: int


def timestamp_to_seconds(value: str) -> int | None:
    """Convert MM:SS or HH:MM:SS into whole seconds; reject invalid clocks."""
    if not isinstance(value, str):
        return None
    try:
        parts = [int(part) for part in value.strip().split(":")]
    except (TypeError, ValueError):
        return None

    if len(parts) == 2:
        minutes, seconds = parts
        if minutes < 0 or not 0 <= seconds < 60:
            return None
        return minutes * 60 + seconds

    if len(parts) == 3:
        hours, minutes, seconds = parts
        if hours < 0 or not 0 <= minutes < 60 or not 0 <= seconds < 60:
            return None
        return hours * 3600 + minutes * 60 + seconds

    return None


def parse_timestamp_range(value: str) -> ParsedTimestampRange | None:
    """Parse one complete timestamp range using accepted dash/word separators."""
    if not isinstance(value, str):
        return None
    match = TIMESTAMP_RANGE_PATTERN.fullmatch(value.strip())
    if match is None:
        return None

    start_text = match.group("start")
    end_text = match.group("end")
    start_seconds = timestamp_to_seconds(start_text)
    end_seconds = timestamp_to_seconds(end_text)
    if (
        start_seconds is None
        or end_seconds is None
        or end_seconds < start_seconds
    ):
        return None

    return ParsedTimestampRange(
        raw=match.group(0),
        start_text=start_text,
        end_text=end_text,
        start_seconds=start_seconds,
        end_seconds=end_seconds,
    )


def find_timestamp_range_texts(text: str) -> list[str]:
    """Return every range-shaped timestamp expression, including invalid ones.

    Audits must see malformed values so they fail rather than disappearing
    during parsing. Production sanitization also removes malformed model claims.
    """
    if not isinstance(text, str) or not text:
        return []
    return [match.group(0) for match in TIMESTAMP_RANGE_PATTERN.finditer(text)]


def find_timestamp_ranges(text: str) -> list[ParsedTimestampRange]:
    """Find valid timestamp ranges in arbitrary answer text."""
    if not isinstance(text, str) or not text:
        return []

    ranges = []
    for match in TIMESTAMP_RANGE_PATTERN.finditer(text):
        parsed = parse_timestamp_range(match.group(0))
        if parsed is not None:
            ranges.append(parsed)
    return ranges


def _has_single_point_location_cue(fragment: str, match: re.Match[str]) -> bool:
    """Detect a single timestamp used as a location rather than a duration."""
    prefix = fragment[:match.start()]
    bare_value = fragment.strip(" \t-*•()[]{}")
    return bool(
        _TIMESTAMP_LOCATION_CUE_SUFFIX_PATTERN.search(prefix)
        or _TIMESTAMP_LOCATION_CUE_WORD_PATTERN.search(fragment)
        or bare_value == match.group(0)
    )


def contains_unverified_timestamp_claims(answer: str) -> bool:
    """Return whether substantive text still contains a model-authored time claim.

    A labelled Relevant timestamps footer is application-owned and is ignored.
    Inline ranges, malformed range-shaped expressions, multiple bare time
    values in one sentence, and single values framed as video locations are
    considered unverified. Ordinary durations without a location cue are not.
    """
    if not isinstance(answer, str) or not answer:
        return False

    substantive = _TIMESTAMP_SUMMARY_LINE_PATTERN.sub("", answer)
    for line in substantive.splitlines():
        for fragment in _TIMESTAMP_SENTENCE_SPLIT_PATTERN.split(line):
            if not fragment.strip():
                continue
            if find_timestamp_range_texts(fragment):
                return True
            time_values = list(TIMESTAMP_VALUE_PATTERN.finditer(fragment))
            if len(time_values) >= 2:
                return True
            if len(time_values) == 1 and _has_single_point_location_cue(
                fragment,
                time_values[0],
            ):
                return True
    return False


def _remove_timestamp_span(
    fragment: str,
    start: int,
    end: int,
) -> str:
    """Remove a timestamp and its immediately preceding location cue."""
    prefix = fragment[:start]
    opening_parenthesis = re.search(r"\(\s*$", prefix)
    cue_prefix = (
        prefix[:opening_parenthesis.start()]
        if opening_parenthesis is not None
        else prefix
    )
    cue_match = _TIMESTAMP_LOCATION_CUE_SUFFIX_PATTERN.search(cue_prefix)
    if cue_match is not None:
        start = cue_match.start()
    elif opening_parenthesis is not None:
        start = opening_parenthesis.start()

    suffix_after = fragment[end:]
    if suffix_after.lstrip().startswith(")"):
        closing_offset = len(suffix_after) - len(suffix_after.lstrip())
        end += closing_offset + 1

    return fragment[:start] + " " + fragment[end:]


def _clean_fragment_spacing(fragment: str) -> str:
    """Clean punctuation/spacing after removing a timestamp phrase."""
    cleaned = re.sub(r"\s+([,.;:!?])", r"\1", fragment)
    cleaned = re.sub(r"([,;:])\s*([,;:])+", r"\1", cleaned)
    cleaned = re.sub(r"\(\s*\)|\[\s*\]", "", cleaned)
    cleaned = re.sub(r"[ \t]{2,}", " ", cleaned)
    return cleaned.strip(_TIMESTAMP_STRIP_EDGE_CHARS).strip()


def _strip_timestamp_claim_fragment(fragment: str) -> str:
    """Remove timestamp claims while preserving non-timestamp answer content."""
    cleaned = fragment
    ranges = list(TIMESTAMP_RANGE_PATTERN.finditer(cleaned))
    for match in reversed(ranges):
        cleaned = _remove_timestamp_span(cleaned, match.start(), match.end())

    # Re-scan after range removal: the same sentence may also contain a
    # separate single-point timestamp such as "around 00:45".
    time_values = list(TIMESTAMP_VALUE_PATTERN.finditer(cleaned))
    if len(time_values) >= 2:
        for match in reversed(time_values):
            cleaned = _remove_timestamp_span(cleaned, match.start(), match.end())
    elif len(time_values) == 1 and _has_single_point_location_cue(
        cleaned,
        time_values[0],
    ):
        match = time_values[0]
        cleaned = _remove_timestamp_span(cleaned, match.start(), match.end())

    return _clean_fragment_spacing(cleaned)


def strip_unverified_timestamp_claims(answer: str) -> str:
    """Remove untrusted model-authored time phrases before trusted stamping.

    Timestamp clauses are removed without discarding surrounding answer content.
    Labelled Relevant timestamps footer lines are always removed. Common
    durations without a video-location cue remain intact.
    """
    if not isinstance(answer, str) or not answer:
        return answer

    cleaned = _TIMESTAMP_SUMMARY_LINE_PATTERN.sub("", answer)
    retained_lines: list[str] = []

    for line in cleaned.splitlines():
        retained_fragments = []
        for fragment in _TIMESTAMP_SENTENCE_SPLIT_PATTERN.split(line):
            if not fragment.strip():
                continue
            cleaned_fragment = _strip_timestamp_claim_fragment(fragment)
            if cleaned_fragment:
                retained_fragments.append(cleaned_fragment)

        if retained_fragments:
            retained_lines.append(" ".join(retained_fragments))

    result = "\n".join(retained_lines)
    result = re.sub(r"\n{3,}", "\n\n", result)
    return result.strip()
