"""Shared parsing and sanitization for YouTube transcript timestamps.

Timestamp claims generated by an LLM are untrusted prose. Production responses
must derive their displayed timestamp metadata from retrieved source intervals
or a validated temporal-retrieval trace. This module contains only deterministic
format parsing and removal helpers; it does not select evidence or know videos.
"""

from __future__ import annotations

from dataclasses import dataclass
import re


# YouTube timestamps are normally MM:SS and become HH:MM:SS for long videos.
_TIMESTAMP_VALUE = r"(?:\d{1,3}:)?\d{1,2}:\d{2}"
_TIMESTAMP_SEPARATOR = r"(?:[-\u2010\u2011\u2012\u2013\u2014\u2015\u2212\ufe58\ufe63\uff0d]|\bto\b|\band\b|&|/)"
TIMESTAMP_RANGE_PATTERN = re.compile(
    rf"(?<![\d:])(?P<start>{_TIMESTAMP_VALUE})"
    rf"\s*{_TIMESTAMP_SEPARATOR}\s*"
    rf"(?P<end>{_TIMESTAMP_VALUE})(?![\d:])",
    re.IGNORECASE,
)
TIMESTAMP_VALUE_PATTERN = re.compile(
    rf"(?<![\d:]){_TIMESTAMP_VALUE}(?![\d:])"
)
_TIMESTAMP_SUMMARY_LINE_PATTERN = re.compile(
    r"(?im)^[ \t]*Relevant timestamps?[ \t]*:[^\r\n]*(?:\r?\n|$)"
)
_TIMESTAMP_CLAUSE_CUE_PATTERN = re.compile(
    r"\b(?:at|around|about|near|from|to|until|timestamp|timecode|time\s*stamp)\b",
    re.IGNORECASE,
)


@dataclass(frozen=True, slots=True)
class ParsedTimestampRange:
    """A validated timestamp interval expressed in the answer."""

    raw: str
    start_text: str
    end_text: str
    start_seconds: int
    end_seconds: int


def timestamp_to_seconds(value: str) -> int | None:
    """Convert MM:SS or HH:MM:SS into whole seconds; reject invalid clocks."""
    if not isinstance(value, str):
        return None
    try:
        parts = [int(part) for part in value.strip().split(":")]
    except (TypeError, ValueError):
        return None

    if len(parts) == 2:
        minutes, seconds = parts
        if minutes < 0 or not 0 <= seconds < 60:
            return None
        return minutes * 60 + seconds

    if len(parts) == 3:
        hours, minutes, seconds = parts
        if hours < 0 or not 0 <= minutes < 60 or not 0 <= seconds < 60:
            return None
        return hours * 3600 + minutes * 60 + seconds

    return None


def parse_timestamp_range(value: str) -> ParsedTimestampRange | None:
    """Parse one complete timestamp range using accepted dash/word separators."""
    if not isinstance(value, str):
        return None
    match = TIMESTAMP_RANGE_PATTERN.fullmatch(value.strip())
    if match is None:
        return None

    start_text = match.group("start")
    end_text = match.group("end")
    start_seconds = timestamp_to_seconds(start_text)
    end_seconds = timestamp_to_seconds(end_text)
    if (
        start_seconds is None
        or end_seconds is None
        or end_seconds < start_seconds
    ):
        return None

    return ParsedTimestampRange(
        raw=match.group(0),
        start_text=start_text,
        end_text=end_text,
        start_seconds=start_seconds,
        end_seconds=end_seconds,
    )


def find_timestamp_ranges(text: str) -> list[ParsedTimestampRange]:
    """Find valid timestamp ranges in arbitrary answer text."""
    if not isinstance(text, str) or not text:
        return []

    ranges = []
    for match in TIMESTAMP_RANGE_PATTERN.finditer(text):
        parsed = parse_timestamp_range(match.group(0))
        if parsed is not None:
            ranges.append(parsed)
    return ranges


def strip_unverified_timestamp_claims(answer: str) -> str:
    """Remove model-authored timestamp summaries/claims before trusted stamping.

    Whole sentence or bullet fragments containing timestamp ranges are removed
    so deleting a range cannot leave misleading or broken prose. A single
    timestamp is removed only when it is explicitly presented as a video
    location (for example, "at 01:20" or "around 01:20"). Ordinary durations,
    ratios, dates, and unrelated numbers are not treated as video locations.
    """
    if not isinstance(answer, str) or not answer:
        return answer

    cleaned = _TIMESTAMP_SUMMARY_LINE_PATTERN.sub("", answer)
    retained_lines: list[str] = []

    for line in cleaned.splitlines():
        # Keep line boundaries and bullet structure for the substantive prose.
        fragments = re.split(r"(?<=[.!?])\s+", line)
        retained_fragments = []
        for fragment in fragments:
            if not fragment.strip():
                continue
            if find_timestamp_ranges(fragment):
                continue

            time_values = list(TIMESTAMP_VALUE_PATTERN.finditer(fragment))
            if time_values and (
                len(time_values) >= 2
                or _TIMESTAMP_CLAUSE_CUE_PATTERN.search(fragment)
            ):
                continue
            retained_fragments.append(fragment.strip())

        if retained_fragments:
            retained_lines.append(" ".join(retained_fragments))

    result = "\n".join(retained_lines)
    result = re.sub(r"\n{3,}", "\n\n", result)
    return result.strip()
